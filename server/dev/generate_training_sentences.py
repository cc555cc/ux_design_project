#generates learning_resource/training_sentences.txt: unique sandwich ordering sentences labelled "service | order",
#for model_learning.py to learn order vocabulary from (run model_learning.py afterwards to train).
#
#templates deliberately avoid generic words ("i'd", "just", "shop", "today", names, times...) because any word that
#reaches 5 observations at 70% one intent is promoted into INTENT_KEYWORDS, and top_level_intent() picks the
#first keyword in a sentence, so a promoted generic word would turn "i'd like to know your hours" into an order.
#
#usage: python dev/generate_training_sentences.py [count]
import random
import sys
from pathlib import Path

OUTPUT = Path(__file__).resolve().parent.parent / "src" / "learning_resource" / "training_sentences.txt"
SEED = 2026

SIZES = ["footlong", "6 inch", "12 inch", "6in", "12in"]
BREADS = ["italian", "wheat", "honey oat", "multigrain", "flatbread", "herbs and cheese", "white", "wrap"]
PROTEINS = ["turkey", "ham", "chicken", "grilled chicken", "roast beef", "steak", "tuna", "meatball", "salami", "veggie patty"]
CHEESES = ["american", "cheddar", "swiss", "provolone", "pepper jack", "mozzarella"]
VEGGIES = ["lettuce", "tomato", "cucumber", "onion", "peppers", "spinach", "pickles", "olives", "jalapenos", "banana peppers"]
SAUCES = ["mayo", "mustard", "honey mustard", "ranch", "chipotle", "bbq", "teriyaki", "oil and vinegar", "sriracha"]

#openers carry the vocabulary worth learning: order-specific verbs and phrases
OPENERS = [
    "can i grab a", "could i grab a", "lemme grab a", "grab me a", "lemme order a", "gimme a", "can i snag a",
    "snag me a", "craving a", "craving me a", "can i order a", "ordering a", "build me a", "fancy a",
    "toss me a", "a",
]

#how the sandwich is described after the opener
CONNECTORS_CHEESE = ["with", "add", "and"]
CONNECTORS_VEG = ["loaded with", "piled with", "with", "add", "and", "throw on", "stuffed with"]
CONNECTORS_SAUCE = ["drizzled with", "with", "add", "dash of", "splash of", "smothered in"]

EXTRAS = [
    "", "", "", "", "toasted", "extra toasted", "lightly toasted", "double meat", "extra cheese", "extra sauce",
]

#modification style sentences, the chatbot handles these mid-order
MODIFICATIONS = [
    "swap the {a} for {b}", "replace the {a} with {b}", "switch the {a} to {b}",
    "hold the {v}", "no {v}", "skip the {v}", "extra {v}", "double {v}",
]


def pick_veggies(rng):
    return rng.sample(VEGGIES, rng.randint(1, 4))


def join_words(items):
    return items[0] if len(items) == 1 else ", ".join(items[:-1]) + " and " + items[-1]


def full_order(rng):
    parts = [rng.choice(OPENERS), rng.choice(SIZES), rng.choice(PROTEINS), "sub on", rng.choice(BREADS)]
    if rng.random() < 0.7:
        parts += [rng.choice(CONNECTORS_CHEESE), rng.choice(CHEESES)]
    if rng.random() < 0.8:
        parts += [rng.choice(CONNECTORS_VEG), join_words(pick_veggies(rng))]
    if rng.random() < 0.7:
        parts += [rng.choice(CONNECTORS_SAUCE), rng.choice(SAUCES)]
    extra = rng.choice(EXTRAS)
    if extra:
        parts.append(extra)
    return " ".join(parts)


def short_order(rng):
    templates = [
        "{opener} {protein} sub",
        "{opener} {size} {protein}",
        "{opener} {protein} on {bread}",
        "{opener} {protein} and {cheese} on {bread}",
        "{size} {protein} on {bread} {extra}",
        "{protein} {cheese} {bread} {size}",
        "{opener} {protein} hoagie with {veg}",
        "{opener} {protein} wrap with {veg} and {sauce}",
    ]
    return rng.choice(templates).format(
        opener=rng.choice(OPENERS), protein=rng.choice(PROTEINS), size=rng.choice(SIZES),
        bread=rng.choice(BREADS), cheese=rng.choice(CHEESES), veg=join_words(pick_veggies(rng)),
        sauce=rng.choice(SAUCES), extra=rng.choice(EXTRAS),
    ).strip()


def modification(rng):
    category = rng.choice([PROTEINS, CHEESES, BREADS, SAUCES])
    a, b = rng.sample(category, 2)
    return rng.choice(MODIFICATIONS).format(a=a, b=b, v=rng.choice(VEGGIES + SAUCES))


def generate(count):
    rng = random.Random(SEED)
    sentences = set()
    makers = [full_order] * 6 + [short_order] * 3 + [modification]
    while len(sentences) < count:
        sentence = " ".join(rng.choice(makers)(rng).split())
        sentences.add(sentence)
    return sorted(sentences, key=lambda _: rng.random())


if __name__ == "__main__":
    count = int(sys.argv[1]) if len(sys.argv) > 1 else 1000
    lines = [f"{sentence} | service | order" for sentence in generate(count)]
    header = "#generated by server/dev/generate_training_sentences.py, format: sentence | top_intent | sub_intent\n"
    OUTPUT.write_text(header + "\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {len(lines)} sentences to {OUTPUT}")
